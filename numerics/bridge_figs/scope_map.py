"""What the numerics of this repository cover, next to the programme's own status labels.

Reads the table "Counts of the authors' labels" of `STATUS_MAP.md` (generated by `tools/make_status_map.py` from the README; the labels are
the authors', not mine) and draws it as a bar chart.  Beside it, a list of what each numerical study in `numerics/` computes, taken from the
README of that study and not from the manuscripts.

The two sides are placed next to each other only to show their scope.  The READMEs of the studies state that they test no bound, estimate,
analytic-domain condition or proof of the programme, and this chart adds no claim about any row of the table: it does not say that any row is
supported, illustrated or contradicted.

    python3 scope_map.py
    python3 scope_map.py --no-show --save-dir figures
"""
import os
import re
import sys

_HERE = os.path.dirname(os.path.realpath(__file__))
_REPO = os.path.dirname(os.path.dirname(_HERE))

STUDIES = [
    ("abelian_first_step", "U(1) Gaussian analogue of the first step on a 4-torus, squares:\nperimeter law and one corner constant, scaling in g and eps"),
    ("corner_locality", "same analogue, other loops: is one constant per corner enough?\nrange, placement against the blocks, gauge, L = 3 and 5"),
    ("bridge_figs", "Spectre outline in the hexagonal lift and in Z^4 (geometry),\nwith one energy comparison; no proof content"),
]


def label_counts(path=os.path.join(_REPO, "STATUS_MAP.md")):
    """[(label, count)] from the table under '## Counts of the authors' labels', in file order."""
    text = open(path, encoding="utf-8").read()
    m = re.search(r"## Counts of the authors' labels\s+\|[^\n]*\n\|[^\n]*\n((?:\|[^\n]*\n?)+)", text)
    if not m:
        raise ValueError("table not found in STATUS_MAP.md")
    out = []
    for line in m.group(1).strip().split("\n"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        out.append((cells[0], int(cells[1])))
    return out


def figure(save=None, show=True):
    import matplotlib
    if not show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    rows = label_counts()
    fig, ax = plt.subplots(1, 2, figsize=(13, 5), gridspec_kw=dict(width_ratios=[1.1, 1]))
    labs = [r[0] for r in rows][::-1]
    vals = [r[1] for r in rows][::-1]
    ax[0].barh(range(len(vals)), vals, color="0.6")
    ax[0].set_yticks(range(len(vals)))
    ax[0].set_yticklabels(labs, fontsize=8)
    ax[0].set_xlabel("rows of the README tables with this label")
    ax[0].set_title("the programme's own status labels (%d rows; from STATUS_MAP.md)" % sum(vals), fontsize=9)
    ax[1].axis("off")
    y = 0.95
    ax[1].text(0, y, "What the numerics in numerics/ compute", fontsize=10, weight="bold", va="top")
    y -= 0.1
    for name, desc in STUDIES:
        ax[1].text(0, y, name, fontsize=9, weight="bold", va="top", family="monospace")
        ax[1].text(0.02, y - 0.05, desc, fontsize=8, va="top")
        y -= 0.22
    ax[1].text(0, y - 0.02, "None of them tests a bound, estimate, domain condition or proof.\nThis chart draws no link between the two sides.", fontsize=8.5,
               va="top", style="italic")
    fig.tight_layout()
    if save:
        os.makedirs(os.path.dirname(save) or ".", exist_ok=True)
        fig.savefig(save, dpi=150)
        print("saved", save)
    if show:
        plt.show()
    plt.close(fig)


def main(argv):
    rows = label_counts()
    print("%d labels, %d rows: %s" % (len(rows), sum(c for _, c in rows), ", ".join("%s %d" % r for r in rows[:4]) + ", ..."))
    d = argv[argv.index("--save-dir") + 1] if "--save-dir" in argv else None
    figure(os.path.join(d, "scope_map.png") if d else None, "--no-show" not in argv)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
