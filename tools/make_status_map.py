#!/usr/bin/env python3
"""Regenerate STATUS_MAP.md from README.md and drafts/.

Mechanical only: the status tables are copied from README.md as written (their
labels are the authors' own), and the open-item index lists, for each label, the
drafts that mention it.  Nothing here assesses the mathematics.

    python3 tools/make_status_map.py          # writes STATUS_MAP.md
"""
import os, re, collections, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README = open(os.path.join(ROOT, 'README.md'), encoding='utf-8').read()

# labels named in the README's own "outstanding work" cells and status report
LABELS = ['R-eval', 'R-round', 'R-att-ext', 'R-member', 'R-far″', 'R-far', 'R-dec', 'R-m′',
          'Wδ-1', 'Wδ-2', 'Wδ-3', 'LF-A', '(S-w)', 'O2′', 'O2', 'O4', 'O6', 'D2.6', 'D2.7',
          'R-I7', 'R-cpl']


def section_tables(md):
    """yield (section title, rows) for every pipe table with a 'Completion' column."""
    lines = md.split('\n')
    title, i = '', 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith('#'):
            title = ln.lstrip('#').strip()
        if ln.startswith('|') and 'Completion' in ln:
            rows, i = [], i + 2
            while i < len(lines) and lines[i].startswith('|'):
                cells = [c.strip() for c in lines[i].strip().strip('|').split('|')]
                # a cell may contain an unescaped '|' only if the author wrote one; keep 3 cols
                if len(cells) >= 3:
                    rows.append((cells[0], cells[1], ' | '.join(cells[2:])))
                i += 1
            yield title, rows
            continue
        i += 1


def strip_md(s):
    return re.sub(r'\*\*', '', s)


def main():
    drafts = sorted(f for f in os.listdir(os.path.join(ROOT, 'drafts'))
                    if f.endswith(('.md', '.tex', '.txt')))
    texts = {f: open(os.path.join(ROOT, 'drafts', f), encoding='utf-8', errors='ignore').read()
             for f in drafts}
    out = ['# Status map', '',
           'Generated by [`tools/make_status_map.py`](tools/make_status_map.py) from `README.md` and `drafts/`. '
           'Do not edit by hand; rerun the script.', '',
           'The status labels below are the authors\' own, copied from the README. This page adds no '
           'assessment of the mathematics. Its only additions are (1) a count of labels per table and '
           '(2) an index of which drafts mention each open-item label, to help a new reader find where '
           'a named item is discussed. A draft that merely mentions a label does not necessarily define or '
           'resolve it; start from the README links.', '']
    allrows = []
    for title, rows in section_tables(README):
        out += [f'## {title}', '', '| Step | Label | Outstanding work (as written in the README) |', '|---|---|---|']
        for a, b, c in rows:
            out.append(f'| {a} | {b} | {c} |')
            allrows.append((title, strip_md(b)))
        out.append('')
    out += ['## Counts of the authors\' labels', '', '| Label | Rows |', '|---|---|']
    cnt = collections.Counter(b for _, b in allrows)
    for lab, n in sorted(cnt.items(), key=lambda kv: -kv[1]):
        out.append(f'| {lab} | {n} |')
    out += ['', '## Open-item index', '',
            'Labels are searched as literal strings in `drafts/*`. Counts are occurrences in the file. '
            '(`R-far` also matches inside `R-far″`, `O2` inside `O2′`.)', '',
            '| Label | Drafts (occurrences) |', '|---|---|']
    for lab in LABELS:
        hits = []
        for f, t in texts.items():
            k = t.count(lab)
            if k:
                hits.append((k, f))
        hits.sort(reverse=True)
        top = hits[:6]
        cell = '; '.join(f'[{f}](drafts/{f}) ({k})' for k, f in top) if top else '(no draft mentions it)'
        more = f'; … and {len(hits) - 6} more' if len(hits) > 6 else ''
        out.append(f'| `{lab}` | {cell}{more} |')
    out += ['', f'*Generated from README.md and {len(drafts)} files in drafts/.*', '']
    open(os.path.join(ROOT, 'STATUS_MAP.md'), 'w', encoding='utf-8').write('\n'.join(out))
    print('wrote STATUS_MAP.md:', len(allrows), 'table rows,', len(drafts), 'drafts scanned')


if __name__ == '__main__':
    main()
